import numpy as np

# Функция для подсчета количества чисел в массиве, которые делятся на 3
def sum_del(array: np.array) -> int:
    # Проверяем делимость каждого элемента массива на 3 и суммируем количество True
    return np.sum(array % 3 == 0)

# Тестовые случаи
def test_sum_del():
    # Тест 1: Массив с положительными и отрицательными числами
    array1 = np.array([1, -3, -6, 7, 9, 12, 14, 18])
    assert sum_del(array1) == 5, "Тест 1 не пройден"

    # Тест 2: Массив без чисел, которые делятся на 3
    array2 = np.array([1, 2, 4, 5, 7, 8])
    assert sum_del(array2) == 0, "Тест 2 не пройден"

    # Тест 3: Массив, состоящий только из чисел, которые делятся на 3
    array3 = np.array([3, 6, 9, 12, 15])
    assert sum_del(array3) == 5, "Тест 3 не пройден"

    # Тест 4: Пустой массив
    array4 = np.array([])
    assert sum_del(array4) == 0, "Тест 4 не пройден"

    # Тест 5: Массив с нулем
    array5 = np.array([0, 3, 6, 9])
    assert sum_del(array5) == 4, "Тест 5 не пройден"

    print("Все тесты успешно пройдены!")

# Запуск тестов
test_sum_del()
